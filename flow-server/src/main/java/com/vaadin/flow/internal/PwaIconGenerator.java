package com.vaadin.flow.internal;

import java.io.IOException;
import java.net.URL;

import com.vaadin.flow.di.Lookup;

/**
 * Generates PWA icons that are not pre-generated by the production build.
 * <p>
 * Resizing an image needs AWT, so the implementation lives in the build tools,
 * which are only available during development. A production application serves
 * the icons generated by the build and has no implementation available through
 * {@link Lookup}.
 * <p>
 * For internal use only. May be renamed or removed in a future release.
 */
public interface PwaIconGenerator {

    /**
     * Generates a PNG icon of the given size from the base image.
     *
     * @param baseImage
     *            the URL of the image to generate the icon from
     * @param width
     *            the width of the icon in pixels
     * @param height
     *            the height of the icon in pixels
     * @return the icon in PNG format
     * @throws IOException
     *             if the base image cannot be read
     */
    byte[] generateIcon(URL baseImage, int width, int height)
            throws IOException;
}
